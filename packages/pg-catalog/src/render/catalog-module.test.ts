import type { Catalog } from '@netvark/catalog-core';

import { beforeAll, describe, expect, it } from 'vitest';

import { readReplayed } from '../test-support/replayed';
import { portableMigrations } from '../test-support/schema';
import {
  FILE_HEADER,
  parseCatalogModule,
  renderCatalogModule,
  renderPublicCatalogModule,
} from './catalog-module';

const tiny: Catalog = {
  format: 1,
  schemas: ['public'],
  extensions: [],
  enums: { mood: ['happy', 'sad'] },
  domains: {},
  tables: {},
};

describe('renderCatalogModule (SPEC 9.1)', () => {
  it('writes the header, the binding, JSON with two-space indentation, and as const, ending in one newline', () => {
    expect(renderCatalogModule(tiny)).toBe(
      `${FILE_HEADER}
export const catalog = {
  "format": 1,
  "schemas": [
    "public"
  ],
  "extensions": [],
  "enums": {
    "mood": [
      "happy",
      "sad"
    ]
  },
  "domains": {},
  "tables": {}
} as const;
`,
    );
  });

  it('binds the public slice as publicCatalog', () => {
    const text = renderPublicCatalogModule({
      format: 1,
      enums: {},
      domains: {},
      tables: {},
    });
    expect(text.split('\n').slice(0, 2)).toEqual([
      FILE_HEADER,
      'export const publicCatalog = {',
    ]);
  });

  it('pins the header text of SPEC 15', () => {
    expect(FILE_HEADER).toBe(
      '// Generated by @netvark/pg-catalog. Do not edit: change the migrations and run `pg-catalog extract`.',
    );
  });
});

describe('parseCatalogModule (SPEC 9.1)', () => {
  let catalog: Catalog;

  beforeAll(async () => {
    catalog = await readReplayed(portableMigrations, ['public', 'audit']);
  });

  it('reads back exactly the catalog a rendered module declares, for a real schema', () => {
    expect(parseCatalogModule(renderCatalogModule(catalog))).toEqual(catalog);
  });

  it('accepts trailing whitespace an editor may add', () => {
    expect(parseCatalogModule(`${renderCatalogModule(tiny)}\n\n`)).toEqual(
      tiny,
    );
  });

  it.each([
    ['an empty file', ''],
    [
      'a module without the terminator',
      'export const catalog = {"format": 1};',
    ],
    ['a module without an assignment', '{"format": 1} as const;'],
  ])('fails with catalog_unreadable for %s', (_title, text) => {
    expect(() => parseCatalogModule(text)).toThrow(
      expect.objectContaining({
        code: 'catalog_unreadable',
        message:
          'the file is not a catalog module written by pg-catalog extract',
      }),
    );
  });

  it('fails with catalog_unreadable for invalid JSON, keeping the parse error as the cause', () => {
    let caught: unknown;
    try {
      parseCatalogModule('export const catalog = {format: 1} as const;');
    } catch (error) {
      caught = error;
    }
    expect(caught).toMatchObject({
      code: 'catalog_unreadable',
      message: 'the catalog module does not hold valid JSON',
    });
    expect((caught as Error).cause).toBeInstanceOf(SyntaxError);
  });

  it.each([
    ['an array', 'export const catalog = [] as const;'],
    [
      'an object without a format',
      'export const catalog = {"tables": {}} as const;',
    ],
  ])('fails with catalog_unreadable for %s', (_title, text) => {
    expect(() => parseCatalogModule(text)).toThrow(
      expect.objectContaining({
        code: 'catalog_unreadable',
        message: 'the catalog module does not declare a catalog',
      }),
    );
  });

  it('fails with catalog_format for another format, telling the reader to extract again', () => {
    expect(() =>
      parseCatalogModule('export const catalog = {"format": 2} as const;'),
    ).toThrow(
      expect.objectContaining({
        code: 'catalog_format',
        message:
          'the catalog module was written in format 2; this version reads format 1, so run pg-catalog extract again',
      }),
    );
  });
});
