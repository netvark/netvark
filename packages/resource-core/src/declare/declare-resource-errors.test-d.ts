/**
 * Every compile error of SPEC 3 and 14, each as a `@ts-expect-error` where
 * TypeScript reports it: above the offending member, or above the call when
 * the requirement is the declaration's as a whole.
 */
import { describe, it } from 'vitest';

import { contactsCatalog } from '../test-support/contacts';
import { TEST_REGISTRIES } from '../test-support/definer';
import { createDeclareResource } from './create-declare-resource';

const declareResource = createDeclareResource({
  catalog: contactsCatalog,
  ...TEST_REGISTRIES,
});

describe('declareResource: names the catalog does not have', () => {
  it('rejects a table outside the public catalog', () => {
    // @ts-expect-error accounts is not a table of the catalog
    declareResource('accounts', { operations: ['get'], fields: {} });
  });

  it('rejects an unknown column, foreign key, and constraint', () => {
    declareResource('contacts', {
      operations: ['get'],
      fields: {
        // @ts-expect-error nick is not a column of contacts
        nick: { access: 'read' },
      },
    });
    declareResource('contacts', {
      operations: ['get'],
      fields: {},
      relationships: {
        // @ts-expect-error name is not the column of a foreign key
        name: { target: () => null, access: 'read' },
      },
    });
    declareResource('contacts', {
      operations: ['get'],
      fields: {},
      rules: {
        // @ts-expect-error contacts_nope is not a constraint
        contacts_nope: { code: 'NOPE' },
      },
    });
  });

  it('rejects an unknown scope, codec, and validator', () => {
    declareResource('contacts', {
      operations: ['get'],
      // @ts-expect-error tenant is not a scope of the definer
      scope: 'tenant',
      fields: {},
    });
    declareResource('contacts', {
      operations: ['get'],
      fields: {
        // @ts-expect-error money is not a codec of the definer
        website: { access: 'read', codec: 'money' },
      },
    });
    declareResource('meetings', {
      operations: ['create'],
      fields: { room: { access: 'immutable' } },
      rules: {
        // @ts-expect-error phone is not a validator of the definer
        meetings_room_check: { validator: 'phone' },
      },
    });
  });

  it('rejects a misspelled member at every level', () => {
    declareResource('contacts', {
      operations: ['get'],
      fields: {},
      // @ts-expect-error relationship is not a member of a declaration
      relationship: {},
    });
    declareResource('contacts', {
      operations: ['get'],
      fields: {
        // @ts-expect-error sortable is not a member of a field declaration
        name: { access: 'read', sortable: true },
      },
    });
  });
});

describe('declareResource: columns declared against SPEC 3.1', () => {
  it('rejects the primary key, a foreign key, and a tsvector as fields', () => {
    declareResource('contacts', {
      operations: ['get'],
      fields: {
        // @ts-expect-error the primary key is the resource id
        id: { access: 'read' },
        // @ts-expect-error organization_id is declared under relationships
        organization_id: { access: 'read' },
        // @ts-expect-error search is named in search.column
        search: { access: 'read' },
      },
    });
  });

  it('rejects an access the column does not allow', () => {
    declareResource('meetings', {
      operations: ['create', 'update'],
      fields: {
        // @ts-expect-error a generated column is read-only
        duration_minutes: { access: 'immutable' },
        // @ts-expect-error an identity column generated by default is read or immutable
        number: { access: 'readWrite' },
      },
    });
    declareResource('audit.changes', {
      operations: ['create'],
      fields: {
        // @ts-expect-error an identity column generated always is read-only
        sequence: { access: 'immutable' },
      },
    });
  });

  it('rejects an access no listed operation writes', () => {
    declareResource('contacts', {
      operations: ['get', 'update'],
      fields: {
        // @ts-expect-error immutable needs the create operation
        kind: { access: 'immutable' },
        name: { access: 'readWrite' },
      },
    });
    declareResource('meetings', {
      operations: ['get'],
      fields: {},
      relationships: {
        // @ts-expect-error readWrite needs the create or update operation
        follow_up_of_id: { target: () => null, access: 'readWrite' },
      },
    });
  });

  it('rejects a column without a wire form unless a codec that accepts it is named', () => {
    declareResource('meetings', {
      operations: ['get'],
      fields: {
        // @ts-expect-error tstzrange has no wire form
        during: { access: 'read' },
      },
    });
    declareResource('organizations', {
      operations: ['get'],
      fields: {
        // @ts-expect-error the range codec does not accept the domain country_code
        country: { access: 'read', codec: 'range' },
      },
    });
  });

  it('rejects a foreign key that spells ids unlike the key it references', () => {
    declareResource('badge_awards', {
      operations: ['get'],
      fields: {},
      relationships: {
        // @ts-expect-error badge_id is a character(4), which spells ids unlike badges.code, a character(6)
        badge_id: { target: () => null, access: 'read' },
      },
    });
  });

  it('rejects a foreign key a relationship cannot carry, and a written scope column', () => {
    declareResource('people', {
      operations: ['get'],
      fields: {},
      relationships: {
        // @ts-expect-error team_slug references teams.slug, which is not its primary key
        team_slug: { target: () => null, access: 'read' },
      },
    });
    declareResource('document_notes', {
      operations: ['get'],
      fields: {},
      relationships: {
        // @ts-expect-error document is a jsonb column, which cannot carry a resource id
        document: { target: () => null, access: 'read', as: 'document' },
      },
    });
    declareResource('contacts', {
      operations: ['create'],
      scope: 'organization',
      fields: { name: { access: 'immutable' } },
      relationships: {
        // @ts-expect-error the scope column is read-only
        organization_id: { target: () => null, access: 'immutable' },
      },
    });
  });
});

describe('declareResource: filters and sorts keyset-core cannot run (SPEC 11.3)', () => {
  it('rejects an operator the keyset type does not take, and isNull on a non-null member', () => {
    declareResource('contacts', {
      operations: ['list'],
      fields: {
        // @ts-expect-error gt is not an operator of arrays
        tags: { access: 'read', filter: ['gt'] },
        // @ts-expect-error name cannot be null
        name: { access: 'read', filter: ['isNull'] },
        nickname: { access: 'read', filter: ['startsWith', 'isNull'] },
      },
      relationships: {
        // @ts-expect-error organization_id cannot be null
        organization_id: {
          target: () => null,
          access: 'read',
          filter: ['isNull'],
        },
      },
    });
  });

  it('rejects filter and sort on a member without a keyset type, and sort on an array', () => {
    declareResource('audit.changes', {
      operations: ['list'],
      fields: {
        // @ts-expect-error jsonb is not filterable
        payload: { access: 'read', filter: ['eq'] },
      },
    });
    declareResource('meetings', {
      operations: ['list'],
      fields: {
        // @ts-expect-error a codec field is not sortable
        during: { access: 'read', codec: 'range', sort: true },
      },
    });
    declareResource('contacts', {
      operations: ['list'],
      fields: {
        // @ts-expect-error an array is not sortable
        tags: { access: 'read', sort: true },
      },
    });
  });
});

describe('declareResource: definitions keyset-core and jsonapi-core refuse (SPEC 11.2)', () => {
  it('rejects an empty or repeated filter', () => {
    declareResource('contacts', {
      operations: ['list'],
      fields: {
        // @ts-expect-error at least one operator
        name: { access: 'read', filter: [] },
        // @ts-expect-error eq is listed twice
        nickname: { access: 'read', filter: ['eq', 'eq'] },
      },
      relationships: {
        // @ts-expect-error in is listed twice
        organization_id: {
          target: () => null,
          access: 'read',
          filter: ['in', 'in'],
        },
      },
    });
  });

  it('rejects a filtered or sortable name outside keyset-core field names', () => {
    declareResource('contacts', {
      operations: ['list'],
      fields: {
        // @ts-expect-error not a keyset-core field name
        name: { access: 'read', as: 'größe', filter: ['eq'] },
        // @ts-expect-error not a keyset-core field name
        nickname: { access: 'read', as: 'nick name', sort: true },
        email: { access: 'read', as: 'e mail' },
      },
    });
  });

  it('rejects a filtered member named or, or q with search', () => {
    declareResource('contacts', {
      operations: ['list'],
      fields: {
        // @ts-expect-error the filter disjunction
        name: { access: 'read', as: 'or', filter: ['eq'] },
        // @ts-expect-error the search parameter
        nickname: { access: 'read', as: 'q', filter: ['eq'] },
      },
      search: { column: 'search' },
    });
    declareResource('contacts', {
      operations: ['list'],
      fields: { name: { access: 'read', as: 'q', filter: ['eq'] } },
    });
  });
});
