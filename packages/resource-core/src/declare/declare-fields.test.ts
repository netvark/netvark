import { describe, expect, it } from 'vitest';

import {
  catalogOf,
  column,
  domain,
  table,
  untypedDeclare,
} from '../test-support/catalog-builder';
import { contactsCatalog } from '../test-support/contacts';
import { typeErrorOf } from '../test-support/failure';

const declare = untypedDeclare();
const fields =
  (target: string, operations: ReadonlyArray<string>, value: unknown) => () =>
    declare(target, { operations, fields: value });

describe('declareResource: what a column may be declared as (SPEC 3.1)', () => {
  it('refuses unknown columns, prototype names included', () => {
    expect(
      typeErrorOf(fields('contacts', ['get'], { nick: { access: 'read' } })),
    ).toBe('contacts.fields.nick: "nick" is not a column of contacts');
    expect(
      typeErrorOf(
        fields('contacts', ['get'], { constructor: { access: 'read' } }),
      ),
    ).toBe(
      'contacts.fields.constructor: "constructor" is not a column of contacts',
    );
  });

  it('refuses the primary key, a foreign key, and a tsvector column as fields', () => {
    expect(
      typeErrorOf(fields('contacts', ['get'], { id: { access: 'read' } })),
    ).toBe('contacts.fields.id: the primary key is the resource id');
    expect(
      typeErrorOf(
        fields('contacts', ['get'], { organization_id: { access: 'read' } }),
      ),
    ).toBe(
      'contacts.fields.organization_id: a foreign-key column is declared under relationships',
    );
    expect(
      typeErrorOf(fields('contacts', ['get'], { search: { access: 'read' } })),
    ).toBe(
      'contacts.fields.search: a tsvector column is declared as search.column',
    );
  });

  it('refuses the scope column as a field when it is not a foreign key', () => {
    const tenants = untypedDeclare(
      catalogOf({
        notes: table('notes', {
          id: column({ type: 'uuid' }),
          tenant: column(),
        }),
      }),
      { scopes: { tenant: { column: 'tenant' } } },
    );
    expect(
      typeErrorOf(() =>
        tenants('notes', {
          operations: ['get'],
          scope: 'tenant',
          fields: { tenant: { access: 'read' } },
        }),
      ),
    ).toBe(
      'notes.fields.tenant: the scope column is written by the server, never declared as a field',
    );
  });

  it('refuses an access the column does not allow', () => {
    expect(
      typeErrorOf(
        fields('meetings', ['create'], {
          duration_minutes: { access: 'immutable' },
        }),
      ),
    ).toBe(
      'meetings.fields.duration_minutes.access: a generated column is read-only',
    );
    expect(
      typeErrorOf(
        fields('audit.changes', ['create'], {
          sequence: { access: 'immutable' },
        }),
      ),
    ).toBe(
      'audit.changes.fields.sequence.access: an identity column generated always is read-only',
    );
    expect(
      typeErrorOf(
        fields('meetings', ['create', 'update'], {
          number: { access: 'readWrite' },
        }),
      ),
    ).toBe(
      'meetings.fields.number.access: an identity column generated by default is read or immutable',
    );
    expect(() =>
      declare('meetings', {
        operations: ['create'],
        fields: { number: { access: 'immutable' } },
      }),
    ).not.toThrow();
  });

  it('refuses an access no listed operation writes (SPEC 3.3)', () => {
    expect(
      typeErrorOf(
        fields('contacts', ['get'], { kind: { access: 'immutable' } }),
      ),
    ).toBe('contacts.fields.kind.access: immutable needs the create operation');
    expect(
      typeErrorOf(fields('contacts', ['list'], { name: { access: 'write' } })),
    ).toBe(
      'contacts.fields.name.access: write needs the create or update operation',
    );
  });
});

describe('declareResource: codecs and wire forms (SPEC 3.1, 5.1, 7.1)', () => {
  it('requires a codec for a column without a wire form', () => {
    expect(
      typeErrorOf(fields('meetings', ['get'], { during: { access: 'read' } })),
    ).toBe(
      'meetings.fields.during: type tstzrange has no wire form; name a codec',
    );
    expect(() =>
      declare('meetings', {
        operations: ['get'],
        fields: { during: { access: 'read', codec: 'range' } },
      }),
    ).not.toThrow();
  });

  it('refuses an unknown codec and one that does not accept the column type', () => {
    expect(
      typeErrorOf(
        fields('contacts', ['get'], {
          website: { access: 'read', codec: 'money' },
        }),
      ),
    ).toBe(
      'contacts.fields.website.codec: "money" is not a codec of createDeclareResource',
    );
    expect(
      typeErrorOf(
        fields('contacts', ['get'], {
          website: { access: 'read', codec: 'range' },
        }),
      ),
    ).toBe(
      'contacts.fields.website.codec: codec "range" does not accept type text',
    );
    expect(
      typeErrorOf(
        fields('contacts', ['get'], {
          tags: { access: 'read', codec: 'phone' },
        }),
      ),
    ).toBe(
      'contacts.fields.tags.codec: codec "phone" does not accept type text[]',
    );
  });

  it('reports a domain the catalog does not hold at the field', () => {
    const broken = untypedDeclare(
      catalogOf({
        notes: table('notes', {
          id: column({ type: 'uuid' }),
          body: column({ type: 'nope', typeKind: 'domain' }),
        }),
      }),
    );
    expect(
      typeErrorOf(() =>
        broken('notes', {
          operations: ['get'],
          fields: { body: { access: 'read' } },
        }),
      ),
    ).toBe('notes.fields.body: domain nope is not in the catalog');
  });
});

describe('declareResource: domain CHECKs without a rule (SPEC 3.6)', () => {
  const withoutDomains = untypedDeclare(contactsCatalog, {});

  it('requires the definer to cover them when the field is written, directly or through an array', () => {
    expect(
      typeErrorOf(() =>
        withoutDomains('contacts', {
          operations: ['create'],
          fields: { email: { access: 'immutable' } },
        }),
      ),
    ).toBe(
      "contacts.fields.email: domain email's CHECK email_check has no rule; give it a validator in createDeclareResource domains",
    );
    expect(() =>
      withoutDomains('contacts', {
        operations: ['get'],
        fields: { email: { access: 'read' } },
      }),
    ).not.toThrow();
    expect(() =>
      declare('meetings', {
        operations: ['create'],
        fields: { attendees: { access: 'immutable' } },
      }),
    ).not.toThrow();
  });

  it('follows the chain of base domains', () => {
    const nested = untypedDeclare(
      catalogOf(
        {
          notes: table('notes', {
            id: column({ type: 'uuid' }),
            code: column({ type: 'short_code', typeKind: 'domain' }),
          }),
        },
        {
          code: domain('code', {
            constraints: { code_check: { kind: 'check', rule: null } },
          }),
          short_code: domain('short_code', {
            type: 'code',
            typeKind: 'domain',
          }),
        },
      ),
    );
    expect(
      typeErrorOf(() =>
        nested('notes', {
          operations: ['create'],
          fields: { code: { access: 'immutable' } },
        }),
      ),
    ).toBe(
      "notes.fields.code: domain code's CHECK code_check has no rule; give it a validator in createDeclareResource domains",
    );
  });
});
