/**
 * The storage contract's schema (SPEC 12.9) as SQL text, applied in order:
 * workspaces, and tasks scoped to a workspace, with a column of each kind
 * an adapter maps: every wire form, an array, JSON, a type with a codec,
 * generated columns, a self-reference, a server value, and a default that
 * reads the scope's session parameter, so a case sees what the transaction
 * set. `public-catalog.ts` is what `pg-catalog extract` writes for these
 * migrations; `e2e/resource` proves it current. The schema has no row
 * security, so only the adapter's scope predicate keeps a row in its scope.
 * @ref https://www.postgresql.org/docs/18/functions-admin.html#FUNCTIONS-ADMIN-SET
 * @packageDocumentation
 */

/** The migrations, in the order a harness applies them. */
export const CONTRACT_MIGRATIONS: ReadonlyArray<string> = [
  `create table workspaces (
  id int8 generated by default as identity primary key,
  name text not null constraint workspaces_name_check check (char_length(name) between 1 and 80),
  created_in text default current_setting('contract.workspace_id', true)
);

create table tasks (
  id uuid primary key default gen_random_uuid(),
  workspace_id int8 not null references workspaces (id),
  title text not null constraint tasks_title_check check (char_length(title) between 1 and 200),
  estimate numeric(6, 2),
  points int8,
  due_on date,
  starts_at timestamptz,
  tags text[] not null default '{}',
  details jsonb,
  done boolean not null default false,
  location point,
  location_text text generated always as (location::text) stored,
  secret text,
  has_secret boolean generated always as (secret is not null) stored,
  parent_id uuid references tasks (id),
  created_by uuid not null,
  created_in text default current_setting('contract.workspace_id', true),
  constraint tasks_workspace_id_title_key unique (workspace_id, title)
);
`,
];

/**
 * Empties the fixture's tables and inserts the seed: workspaces 1 and 2,
 * and workspace 9 holding a task whose `starts_at` is `infinity`, a value
 * with no read form. Identities restart, and the next workspace is 10.
 * `reset()` runs it before every case.
 */
export const CONTRACT_SEED: string = `truncate table tasks, workspaces restart identity;
insert into workspaces (id, name) values (1, 'One'), (2, 'Two'), (9, 'Unreadable');
insert into tasks (id, workspace_id, title, starts_at, created_by)
  values ('00000000-0000-4000-8000-000000000009', 9, 'Forever', 'infinity', '00000000-0000-4000-8000-0000000000aa');
select setval(pg_get_serial_sequence('workspaces', 'id'), 9);
`;
