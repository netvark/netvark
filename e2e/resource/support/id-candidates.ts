const BY_BASE: Readonly<Record<string, ReadonlyArray<string>>> = {
  int2: INTEGERS,
  int4: INTEGERS,
  int8: INTEGERS,
  float4: FLOATS,
  float8: FLOATS,
  numeric: NUMERICS,
  bool: BOOLEANS,
  date: DATES,
  timestamp: LOCALS,
  timestamptz: INSTANTS,
  uuid: UUIDS,
};

/** The candidate texts for a key of the base type `base`, an enum's `labels` among them. */
export function idCandidates(
  base: string,
  labels: ReadonlyArray<string> | undefined,
): ReadonlyArray<string> {
  const list = labels === undefined ? (BY_BASE[base] ?? TEXTS) : TEXTS;
  const options = labels ?? [];
  return [
    ...new Set([
      ...list,
      ...options,
      ...options.map((label) => label.toUpperCase()),
      ...options.map((label) => ` ${label}`),
    ]),
  ];
}
