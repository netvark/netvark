/**
 * The tables of `schema.ts` as a Drizzle application declares them: each
 * column under a camelCase property with its SQL name, the status as a
 * `pgEnum`, and the generated `tsvector` through a custom type. The schema
 * object holds the enum too, as `import * as schema` would; the Drizzle
 * definer ignores the members that are not tables.
 * @ref https://orm.drizzle.team/docs/sql-schema-declaration
 * @ref https://orm.drizzle.team/docs/custom-types
 */
import {
  boolean,
  customType,
  date,
  integer,
  numeric,
  pgEnum,
  pgTable,
  serial,
  text,
  timestamp,
  uuid,
} from 'drizzle-orm/pg-core';

const tsvector = customType<{ data: string }>({
  dataType: () => 'tsvector',
});

const contactStatus = pgEnum('contact_status', ['lead', 'customer']);

export const contacts = pgTable('contacts', {
  id: uuid('id').primaryKey(),
  firstName: text('first_name').notNull(),
  lastName: text('last_name'),
  age: integer('age'),
  score: numeric('score', { precision: 10, scale: 2 }).notNull(),
  active: boolean('active').notNull(),
  status: contactStatus('status').notNull(),
  tags: text('tags').array().notNull(),
  createdAt: timestamp('created_at', { withTimezone: true }).notNull(),
  birthday: date('birthday'),
  bio: text('bio').notNull(),
  /** Generated by the database (`schema.ts`); read, never written. */
  searchVector: tsvector('search_vector'),
});

export const contactEmails = pgTable('contact_emails', {
  id: serial('id').primaryKey(),
  contactId: uuid('contact_id').notNull(),
  email: text('email').notNull(),
  isPrimary: boolean('is_primary').notNull(),
});

const workHistory = pgTable('work_history', {
  id: serial('id').primaryKey(),
  contactId: uuid('contact_id').notNull(),
  company: text('company').notNull(),
  startDate: date('start_date').notNull(),
});

export const schema = { contactStatus, contacts, contactEmails, workHistory };
